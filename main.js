let ahkProcess = null;

function getAhkPaths() {
    const exeDir = path.dirname(process.execPath);
    const resourcesPath = path.join(exeDir, 'resources', 'autohotkey');
    const devPath = path.join(__dirname, 'autohotkey');
    const ahkBinDir = fs.existsSync(resourcesPath) ? resourcesPath : devPath;

    const runtimeDir = process.env.PORTABLE_EXECUTABLE_DIR
        || path.dirname(process.execPath)
        || devPath;

    return {
        exe:    path.join(ahkBinDir, 'AutoHotkey64.exe'),
        script: path.join(ahkBinDir, 'heidi-hotkeys.ahk'),
        config: path.join(runtimeDir, 'heidi-config.ini'),
        slots:  path.join(runtimeDir, 'heidi-slots.json'),
        dir:    runtimeDir
    };
}

function launchAHK() {
    if (process.platform !== 'win32') return;
    const { exe, script } = getAhkPaths();
    if (!fs.existsSync(exe)) { console.error('AutoHotkey64.exe not found at:', exe); return; }
    if (!fs.existsSync(script)) { console.error('heidi-hotkeys.ahk not found at:', script); return; }
    try {
        ahkProcess = spawn(exe, [script], { detached: false, stdio: 'ignore', windowsHide: true });
        ahkProcess.on('error', (e) => console.error('AHK launch error:', e.message));
        ahkProcess.on('exit', (code) => { console.log('AHK exited with code:', code); ahkProcess = null; });
        console.log('AutoHotkey launched, PID:', ahkProcess.pid);
    } catch (e) { console.error('Failed to launch AHK:', e.message); }
}

function killAHK() {
    if (ahkProcess) { try { ahkProcess.kill(); } catch(e) {} ahkProcess = null; }
    if (slotsPoller) { slotsPoller.stop(); slotsPoller = null; }
    if (freedPoller) { freedPoller.stop(); freedPoller = null; }
    if (process.platform === 'win32') {   // no raw or parsed Freed note left on disk after quit
        for (const f of ['freed-clip.txt', 'mna-freed-result.txt']) { try { fs.unlinkSync(path.join(getAhkPaths().dir, f)); } catch (e) {} }
    }
    if (process.platform === 'win32') { try { composedStore().clear(); } catch (e) {} }
}

function writeAhkConfig(examDotPhrase) {
    if (process.platform !== 'win32') return;
    const { config } = getAhkPaths();
    const encoded = (examDotPhrase || '').replace(/\n/g, '\\n').replace(/\r/g, '');
    const ini = `[Heidi]\nExamDotPhrase=${encoded}\n`;
    try { fs.writeFileSync(config, ini, 'utf-8'); } catch (e) { console.error('Failed to write AHK config:', e.message); }
}

let slotsPoller = null;
const captureTracker = createCaptureTracker();

function sendSlotState() {
    if (!mainWindow) return;
    if (captureFailed) {
        mainWindow.webContents.send('capture-result', { success: false, reason: 'capture-failed', message: CAPTURE_FAILED_TEXT,
                                                        hotkeys: currentHotkeys() });
        return;
    }
    const exam = effectiveExam();
    mainWindow.webContents.send('capture-result', {
        success: true,
        hpiLoaded: !!slots.hpi,
        apLoaded: !!slots.ap,
        examLoaded: !!exam,
        hpiPreview: slots.hpi ? slots.hpi.substring(0, 80) : null,
        apPreview: effectiveAp() ? effectiveAp().substring(0, 80) : null,
        examPreview: exam ? exam.substring(0, 80) : null,
        bulletsLoading: false,
        library: libraryUiState(),
        hotkeys: currentHotkeys()
    });
}

// Polls heidi-slots.json every 250 ms by mtime (fs.watch doesn't fire on UNC/network paths).
function watchSlotsFile() {
    if (process.platform !== 'win32') return;
    const { slots: slotsPath } = getAhkPaths();
    captureTracker.init(fs.existsSync(slotsPath));
    slotsPoller = createMtimePoller(slotsPath, readSlotsFile).start();
}

// Returns false on a read/parse failure so the poller retries (e.g. AHK mid-write).
function readSlotsFile() {
    const { slots: slotsPath } = getAhkPaths();
    try {
        if (!fs.existsSync(slotsPath)) return false;
        const data = parseSlotsJson(fs.readFileSync(slotsPath, 'utf-8'));
        if (data.hpi !== undefined) slots.hpi = data.hpi || null;
        if (data.ap  !== undefined) slots.ap  = data.ap  || null;
        const ts = data.timestamp != null ? String(data.timestamp) : null;
        const isNewCapture = captureTracker.observe(ts);  // the leftover file at launch is not a new capture
        if (isNewCapture) {
            currentSource = 'heidi'; freedExam = '';
            freedCapture.resetDuplicateGuard();           // the same Freed note captured later must re-adopt
            beginCapture(ts);                             // always drop the previous patient's library text
            captureFailed = isCaptureFailure({ failed: data.failed, hpi: slots.hpi, ap: slots.ap });
            if (captureFailed) { slots.hpi = null; slots.ap = null; }
        }
        sendSlotState();
        if (isNewCapture && !captureFailed && slots.ap) startLibraryFlow('heidi', ts);
        return true;
    } catch (e) { console.error('Failed to read slots file:', e.message); return false; }
}

