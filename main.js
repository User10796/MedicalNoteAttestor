function registerHotkeys() {
    try {
        globalShortcut.unregisterAll();

        const hk = currentHotkeys();
        const captureKey = hk.capture;
        const paste1Key  = hk.pasteHpi;
        const paste2Key  = hk.pasteExam;
        const paste3Key  = hk.pasteAp;
        const hpiKey     = store.get('hpiHotkey')     || 'PageUp';
        const apKey      = store.get('apHotkey')      || 'PageDown';

        const tryRegister = (key, fn) => {
            try {
                if (key) {
                    const ok = globalShortcut.register(key, fn);
                    console.log(`Hotkey "${key}": ${ok ? 'registered OK' : 'FAILED TO REGISTER'}`);
                }
            } catch (e) {
                console.error(`Hotkey "${key}" threw: ${e.message}`);
            }
        };

        if (process.platform !== 'win32') {
            tryRegister(captureKey, () => { performCapture().catch(e => console.error(e)); });
            tryRegister(paste1Key,  () => pasteSlot('hpi'));
            tryRegister(paste2Key,  () => pasteSlot('exam'));
            tryRegister(paste3Key,  () => pasteSlot('ap'));
        }
        // Optional "Open payer picker" hotkey (unbound by default). AHK doesn't handle it; Electron does.
        if (hk.openPicker) tryRegister(hk.openPicker, () => { const r = openPickerManually(); if (!r.ok && mainWindow) mainWindow.webContents.send('source-notice', r.message); });

        // Legacy single-section hotkeys — keep on all platforms as fallback
        tryRegister(hpiKey, () => extractAndCopySection('hpi'));
        tryRegister(apKey,  () => extractAndCopySection('ap'));

    } catch (err) {
        console.error('registerHotkeys failed:', err.message);
    }
}

async function extractAndCopySection(section) {
    try {
        // Send Ctrl+A then Ctrl+C to the foreground window (e.g. Heidi)
        const psScript = "Add-Type -AssemblyName System.Windows.Forms; Start-Sleep -Milliseconds 50; [System.Windows.Forms.SendKeys]::SendWait('^a'); Start-Sleep -Milliseconds 100; [System.Windows.Forms.SendKeys]::SendWait('^c'); Start-Sleep -Milliseconds 100;";
        execSync(`powershell -NoProfile -Command "${psScript}"`, { timeout: 3000 });
    } catch (e) {
        console.error('Failed to auto-copy from foreground window:', e);
    }

    // Small delay to let clipboard populate
    await new Promise(r => setTimeout(r, 150));

    const text = clipboard.readText();
    if (!text) return;

    let extracted;
    if (section === 'hpi') {
        extracted = extractHPI(text);
    } else {
        extracted = extractAP(text);
    }

    if (extracted) {
        clipboard.writeText(extracted);
        if (mainWindow) {
            mainWindow.webContents.send('section-copied', section);
        }
    }
}

function extractHPI(text) {
    let hpiStart = -1;
    for (const header of HPI_HEADERS) {
        const idx = text.indexOf(header);
        if (idx !== -1) {
            hpiStart = idx + header.length;
            break;
        }
    }
    if (hpiStart === -1) {
        console.log('HPI header not found in text. First 200 chars:', text.substring(0, 200));
        return null;
    }
    const ap = findAPStart(text);
    if (!ap || ap.index <= hpiStart) {
        console.log('A&P header not found after HPI');
        return null;
    }
    return cleanUpText(text.substring(hpiStart, ap.index));
}

function extractAP(text) {
    const ap = findAPStart(text);
    if (!ap) {
        console.log('A&P header not found in text. First 500 chars:', text.substring(0, 500));
        return null;
    }
    console.log('Found A&P header at index', ap.index, ':', text.substring(ap.index, ap.index + 30));
    return cleanUpText(text.substring(ap.index + ap.length));
}

function cleanUpText(text) {
    let cleaned = text.replace(/\*\*/g, '').replace(/\*/g, '');
    cleaned = cleaned.trim();
    const lines = cleaned.split('\n');
    let startIdx = 0;
    for (let i = 0; i < lines.length; i++) {
        if (lines[i].trim()) { startIdx = i; break; }
    }
    return lines.slice(startIdx).join('\n');
}

// ── v2 Slot capture and paste ──────────────────────────────────────────────

async function performCapture() {
    // Empty the clipboard first so a copy that silently fails can't "capture" stale text.
    clipboard.clear();
    // Step 1: Auto-trigger Ctrl+A + Ctrl+C in the active foreground window (Heidi)
    try {
        const psScript = [
            'Add-Type -AssemblyName System.Windows.Forms;',
            'Start-Sleep -Milliseconds 50;',
            '[System.Windows.Forms.SendKeys]::SendWait("^a");',
            'Start-Sleep -Milliseconds 80;',
            '[System.Windows.Forms.SendKeys]::SendWait("^c");',
            'Start-Sleep -Milliseconds 80;'
        ].join(' ');
        execSync(`powershell -NoProfile -Command "${psScript}"`, { timeout: 3000 });
    } catch (e) {
        console.error('performCapture: SendKeys failed:', e.message);
    }

    // Step 2: Wait for clipboard to settle
    await new Promise(r => setTimeout(r, 150));

    // Step 3: Read and parse clipboard
    const text = clipboard.readText();
    const captureTs = String(Date.now());
    beginCapture(captureTs);
    slots.hpi = (text && extractHPI(text)) || null;
    slots.ap  = (text && extractAP(text))  || null;
    captureFailed = isCaptureFailure({ text, hpi: slots.hpi, ap: slots.ap });
    if (captureFailed) {
        slots.hpi = null; slots.ap = null;
        sendSlotState();
        return;
    }
    const exam = getExamSlot();
    if (slots.ap) startLibraryFlow('heidi', captureTs);

    if (mainWindow) mainWindow.webContents.send('capture-result', {
        success: true,
        hpiLoaded:    !!slots.hpi,
        apLoaded:     !!slots.ap,
        examLoaded:   !!exam,
        hpiPreview:   slots.hpi ? slots.hpi.substring(0, 80) : null,
        apPreview:    slots.ap  ? slots.ap.substring(0, 80)  : null,
        examPreview:  exam       ? exam.substring(0, 80)      : null,
        bulletsLoading: !!slots.ap
    });

    // Step 4: Fire bullet enrichment in background (Heidi profile: actionItems true, unchanged)
    if (slots.ap && profiles.get('heidi').actionItems) {
        const originalAP = slots.ap;
        extractActionItems(originalAP).then(bullets => {
            if (bullets && bullets.trim() && slots.ap === originalAP) {
                slots.ap = originalAP + '\n\n' + bullets;
            }
            if (mainWindow) mainWindow.webContents.send('bullets-ready', {
                apPreview: slots.ap ? slots.ap.substring(0, 80) : null
            });
        });
    }
}

function pasteSlot(slotName) {
    let content;
    if      (slotName === 'hpi')  content = slotContent('hpi', pasteState()) || null;
    else if (slotName === 'exam') content = effectiveExam();
    else if (slotName === 'ap')   content = effectiveAp();

    if (content && content.trim()) {
        clipboard.writeText(content);
        if (mainWindow) mainWindow.webContents.send('slot-pasted', slotName);

        // Auto-paste into the active window (Citrix) via PowerShell SendKeys
        setTimeout(() => {
            try {
                const psScript = [
                    'Add-Type -AssemblyName System.Windows.Forms;',
                    'Start-Sleep -Milliseconds 80;',
                    '[System.Windows.Forms.SendKeys]::SendWait("^v");'
                ].join(' ');
                execSync(`powershell -NoProfile -Command "${psScript}"`,
                    { timeout: 3000 });
            } catch (e) {
                console.error('pasteSlot: SendKeys Ctrl+V failed:', e.message);
            }
        }, 100);

    } else if (captureFailed) {
        sendSlotState();   // re-show "Capture failed — nothing to paste"
    } else {
        if (mainWindow) mainWindow.webContents.send('slot-empty', slotName);
    }
}

