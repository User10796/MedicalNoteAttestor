// Captures the screen, shows a fullscreen overlay for region selection,
// returns the cropped NativeImage as a PNG data URL.

let screenshotImage = null; // NativeImage of full screen capture

ipcMain.handle('start-screen-capture', async () => {
    try {
        // Use center of main window to find correct display, fall back to primary
        const mainBounds = mainWindow.getBounds();
        const mainCenter = {
            x: mainBounds.x + Math.floor(mainBounds.width / 2),
            y: mainBounds.y + Math.floor(mainBounds.height / 2)
        };
        const allDisplays = screen.getAllDisplays();
        const primaryDisplay = screen.getPrimaryDisplay();
        let display = allDisplays.find(d =>
            mainCenter.x >= d.bounds.x &&
            mainCenter.x < d.bounds.x + d.bounds.width &&
            mainCenter.y >= d.bounds.y &&
            mainCenter.y < d.bounds.y + d.bounds.height
        ) || primaryDisplay;
        console.log('Capturing display:', display.id, 'bounds:', display.bounds);

        // Hide main window so it's not in the screenshot
        mainWindow.hide();
        await new Promise(r => setTimeout(r, 300));

        // Capture the screen
        const sources = await desktopCapturer.getSources({
            types: ['screen'],
            thumbnailSize: {
                width: display.bounds.width * display.scaleFactor,
                height: display.bounds.height * display.scaleFactor
            }
        });

        const source = sources.find(s => String(s.display_id) === String(display.id)) || sources[0];

        if (!source) {
            if (mainWindow && !mainWindow.isDestroyed()) {
                mainWindow.show(); mainWindow.focus(); mainWindow.setAlwaysOnTop(true);
            }
            return { success: false, error: 'No screen source found' };
        }

        screenshotImage = source.thumbnail;

        // Create overlay for selection — no fullscreen to avoid Citrix security blanking
        overlayWindow = new BrowserWindow({
            x: display.bounds.x,
            y: display.bounds.y,
            width: display.bounds.width,
            height: display.bounds.height,
            frame: false,
            alwaysOnTop: true,
            fullscreen: false,
            resizable: false,
            movable: false,
            skipTaskbar: true,
            webPreferences: {
                nodeIntegration: false,
                contextIsolation: true,
                preload: path.join(__dirname, 'overlay-preload.js')
            }
        });

        overlayWindow.loadFile(path.join(__dirname, 'overlay.html'));

        overlayWindow.webContents.on('did-finish-load', () => {
            const dataUrl = screenshotImage.toDataURL();
            overlayWindow.webContents.send('set-screenshot', dataUrl);
        });

        // Wait for selection or cancel
        return new Promise((resolve) => {
            const cleanup = () => {
                if (overlayWindow && !overlayWindow.isDestroyed()) {
                    overlayWindow.close();
                }
                overlayWindow = null;
                mainWindow.show();
                mainWindow.focus();
                mainWindow.setAlwaysOnTop(true);
            };

            ipcMain.once('selection-done', (event, rect) => {
                // rect = { x, y, width, height } in screen pixels
                if (rect && rect.width > 5 && rect.height > 5) {
                    const scaleFactor = display.scaleFactor;
                    const cropped = screenshotImage.crop({
                        x: Math.round(rect.x * scaleFactor),
                        y: Math.round(rect.y * scaleFactor),
                        width: Math.round(rect.width * scaleFactor),
                        height: Math.round(rect.height * scaleFactor)
                    });
                    cleanup();
                    resolve({ success: true, imageDataUrl: cropped.toDataURL() });
                } else {
                    cleanup();
                    resolve({ success: false, cancelled: true });
                }
            });

            ipcMain.once('selection-cancel', () => {
                cleanup();
                resolve({ success: false, cancelled: true });
            });

            overlayWindow.on('closed', () => {
                overlayWindow = null;
                // If closed without selection
                mainWindow.show();
                mainWindow.setAlwaysOnTop(true);
                resolve({ success: false, cancelled: true });
            });
        });
    } catch (err) {
        console.error('Screen capture error:', err);
        try {
            if (mainWindow && !mainWindow.isDestroyed()) {
                mainWindow.show(); mainWindow.focus(); mainWindow.setAlwaysOnTop(true);
            }
            if (overlayWindow && !overlayWindow.isDestroyed()) {
                overlayWindow.close(); overlayWindow = null;
            }
        } catch (e) { /* ignore cleanup errors */ }
        return { success: false, error: err.message };
    }
});

